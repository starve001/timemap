def catmull_rom_chain(pts: list[list[float]], samples_per_seg: int = 5) -> list[list[float]]:
    if len(pts) < 3:
        return [[round(p[0], 3), round(p[1], 3)] for p in pts]
    ext = [pts[0]] + pts + [pts[-1]]
    out: list[list[float]] = []
    for i in range(1, len(ext) - 2):
        p0, p1, p2, p3 = ext[i - 1], ext[i], ext[i + 1], ext[i + 2]
        for s in range(samples_per_seg):
            t = s / samples_per_seg
            t2 = t * t
            t3 = t2 * t
            x = 0.5 * ((2 * p1[0]) + (-p0[0] + p2[0]) * t + (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * t2 + (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * t3)
            y = 0.5 * ((2 * p1[1]) + (-p0[1] + p2[1]) * t + (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * t2 + (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * t3)
            pt = [round(x, 3), round(y, 3)]
            if not out or out[-1] != pt:
                out.append(pt)
    end = [round(pts[-1][0], 3), round(pts[-1][1], 3)]
    if out[-1] != end:
        out.append(end)
    # 保证首尾精确等于锚点（防无缝拼接偏移）
    out[0] = [round(pts[0][0], 3), round(pts[0][1], 3)]
    out[-1] = end
    return out


def smooth_closed_ring(pts: list[list[float]], samples_per_seg: int = 4) -> list[list[float]]:
    n = len(pts)
    out: list[list[float]] = []
    for i in range(n):
        p0 = pts[(i - 1) % n]
        p1 = pts[i]
        p2 = pts[(i + 1) % n]
        p3 = pts[(i + 2) % n]
        for s in range(samples_per_seg):
            t = s / samples_per_seg
            t2 = t * t
            t3 = t2 * t
            x = 0.5 * ((2 * p1[0]) + (-p0[0] + p2[0]) * t + (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * t2 + (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * t3)
            y = 0.5 * ((2 * p1[1]) + (-p0[1] + p2[1]) * t + (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * t2 + (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * t3)
            pt = [round(x, 3), round(y, 3)]
            if not out or out[-1] != pt:
                out.append(pt)
    if out[0] != out[-1]:
        out.append(list(out[0]))
    return out


def load_10m_lake_geom(lake_name: str) -> dict | None:
    shp = CACHE / "unpacked" / "ne_10m_lakes" / "ne_10m_lakes.shp"
    if not shp.exists():
        return None
    with shapefile.Reader(str(shp)) as sf:
        flds = [f[0].lower() for f in sf.fields[1:]]
        nm_i = flds.index("name")
        for sr in sf.iterShapeRecords():
            if str(sr.record[nm_i] or "").strip() == lake_name:
                g = sr.shape.__geo_interface__
                # round to 3 decimals
                def rnd(c):
                    return [round(c[0], 3), round(c[1], 3)] if isinstance(c[0], (int, float)) else [rnd(x) for x in c]
                return {"type": g["type"], "coordinates": rnd(g["coordinates"])}
    return None


